"""Navigation and link discovery for the mkdocs-material site.

The site is generated by ``mkdocs-material``, which renders the whole
``nav:`` tree of ``mkdocs.yml`` into the sidebar.  Parsing that sidebar gives us
the human readable outline (section titles included) while a breadth-first
crawl of ``<a href>`` links catches pages that are not referenced from the nav.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Iterator, Sequence
from urllib.parse import urlsplit

from .htmltree import Node, parse
from .util import normalize_url, origin_of

#: Top level directories that never contain content pages.
DEFAULT_SKIP_PREFIXES: tuple[str, ...] = (
    "assets/",
    "search/",
    "stylesheets/",
    "javascripts/",
)


@dataclass(frozen=True)
class NavItem:
    """One entry of the site navigation."""

    title: str
    href: str | None = None
    children: tuple["NavItem", ...] = field(default_factory=tuple)

    def walk(self, depth: int = 0) -> Iterator[tuple["NavItem", int]]:
        """Yield ``(item, depth)`` for this item and every descendant."""
        yield self, depth
        for child in self.children:
            yield from child.walk(depth + 1)

    def flat(self) -> list["NavItem"]:
        return [item for item, _ in self.walk()]


def parse_nav(html: str, page_url: str) -> list[NavItem]:
    """Parse the primary navigation out of *html*.

    Returns the top level items; nested navigation becomes ``children``.
    ``href`` is ``None`` for pure section headers.
    """
    root = parse(html)
    nav = root.find("nav", cls="md-nav--primary")
    if nav is None:
        return []
    return _parse_nav_children(nav, page_url)


def _parse_nav_children(nav: Node, page_url: str) -> list[NavItem]:
    list_node = next(
        (child for child in nav.element_children() if child.tag == "ul" and child.has_class("md-nav__list")),
        None,
    )
    if list_node is None:
        return []

    items: list[NavItem] = []
    for li in list_node.element_children():
        if li.tag != "li":
            continue
        items.append(_parse_nav_item(li, page_url))
    return items


def _parse_nav_item(li: Node, page_url: str) -> NavItem:
    nested = next((child for child in li.element_children() if child.tag == "nav"), None)
    anchor = li.find_shallow("a", cls="md-nav__link")

    title = ""
    href: str | None = None
    if anchor is not None:
        label = anchor.find("span", cls="md-ellipsis")
        title = (label.clean_text() if label is not None else anchor.clean_text()).strip()
        raw_href = anchor.get("href").strip()
        if raw_href:
            href = normalize_url(raw_href, page_url)

    if not title:
        title_label = next(
            (child for child in li.element_children() if child.tag == "label"),
            None,
        )
        if title_label is not None:
            title = title_label.clean_text()
    if not title:
        title = href or "(untitled)"

    children = tuple(_parse_nav_children(nested, page_url)) if nested is not None else ()
    return NavItem(title=title, href=href, children=children)


def nav_page_urls(items: Sequence[NavItem]) -> list[str]:
    """Flatten *items* into the ordered list of page URLs."""
    urls: list[str] = []
    seen: set[str] = set()
    for item in items:
        for node, _depth in item.walk():
            if node.href and node.href not in seen:
                seen.add(node.href)
                urls.append(node.href)
    return urls


def extract_page_links(
    html: str,
    page_url: str,
    *,
    skip_prefixes: Sequence[str] = DEFAULT_SKIP_PREFIXES,
) -> list[str]:
    """Return same-site page URLs linked from *html*, in document order."""
    root = parse(html)
    origin = origin_of(page_url)
    found: list[str] = []
    seen: set[str] = set()

    for node in root.iter():
        if node.tag != "a":
            continue
        href = node.get("href").strip()
        if not href or href.startswith(("#", "mailto:", "tel:", "javascript:", "data:")):
            continue
        try:
            absolute = normalize_url(href, page_url)
        except ValueError:
            continue
        if origin_of(absolute) != origin:
            continue
        path = urlsplit(absolute).path
        if not _looks_like_page(path):
            continue
        stripped = path.lstrip("/")
        if any(stripped.startswith(prefix) for prefix in skip_prefixes):
            continue
        if absolute in seen:
            continue
        seen.add(absolute)
        found.append(absolute)
    return found


def extract_title(html: str, default: str = "") -> str:
    """Return the ``<title>`` of *html* (used for the index and reports)."""
    root = parse(html)
    node = root.find("title")
    if node is None:
        heading = root.find("h1")
        return heading.clean_text() if heading is not None else default
    title = node.clean_text()
    return title.split(" - ")[0].strip() if title else default


def _looks_like_page(path: str) -> bool:
    """Heuristic: ``.html`` files and extension-less directories are pages."""
    if path.endswith("/"):
        return True
    last = path.rsplit("/", 1)[-1]
    if not last:
        return True
    return last.endswith((".html", ".htm")) or "." not in last
